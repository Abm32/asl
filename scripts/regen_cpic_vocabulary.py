"""Regenerate the committed CPIC vocabulary snapshot.

    python scripts/regen_cpic_vocabulary.py            # write
    python scripts/regen_cpic_vocabulary.py --check    # CI: byte-compare

Why this file exists, in four measurements taken against the live API on
2026-10-25. Each one is a defect in any consumer that holds a single flat set
of phenotype strings, which is what this package held until now.

**1. CPIC's standardised term list does not cover what CPIC emits.** The
``term`` table defines 11 phenotype terms. The ``diplotype`` table emits 33
distinct ``generesult`` values. 24 of those 33 are absent from the
standardised list.

**2. Matching on the standardised spelling matches nothing.** The term table
writes ``Normal metabolizer``; the diplotype table writes
``Normal Metabolizer``. Across all 33 emitted values and all 11 standardised
terms there is **not one exact-case match**. A consumer that validates against
CPIC's own published vocabulary, spelled as CPIC publishes it, rejects every
real CPIC result. Hence every comparison here is casefolded.

**3. The vocabulary is per gene, and the genes do not agree on a dimension.**
DPYD emits 3 terms, TPMT and NUDT15 5 each (both including
``Possible Intermediate Metabolizer``), CYP2C19 8. SLCO1B1 answers in
*Function* terms rather than *Metabolizer* terms, and G6PD in
``Deficient``/``Normal``/``Variable``. One global set cannot be right for all
of them; it can only be right for whichever gene it was written against.

**4. "Not established" lives at a different layer from every other term.**
``No Result`` appears 251 times as a key in ``recommendation.phenotypes`` and
**never once** as a ``diplotype.generesult``. CPIC models a gene that was not
assayed at the recommendation layer only. A consumer therefore needs two
vocabularies per gene — what a diplotype may resolve to, and what a
recommendation may be keyed on — and the second is strictly larger.

Nothing here is edited by hand. The definitions are CPIC's own
``functionaldef`` and ``geneticdef`` strings, copied verbatim.
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.parse
import urllib.request
from datetime import date
from pathlib import Path

API = "https://api.cpicpgx.org/v1/"
OUT = Path(__file__).resolve().parent.parent / "src" / "asl" / "data"
FILENAME = "CPIC_VOCABULARY.json"

#: Terms the ENGINE may return that CPIC never emits as a diplotype result.
#: ``Indeterminate`` is the clearest case: ``anukriti-pgx-core`` returns it,
#: with confidence 0.0, when it was handed nothing it could resolve. CPIC does
#: publish it for some genes — but not for DPYD, where this package needs it
#: most. Accepting it is a deliberate widening, recorded here rather than
#: smuggled into the gene sets as though CPIC had published it.
ENGINE_TERMS = ("Indeterminate",)


def _get(path: str) -> list[dict]:
    with urllib.request.urlopen(API + path, timeout=120) as response:
        return json.load(response)


def build() -> dict:
    terms = _get("term")
    genes = sorted({g["symbol"] for g in _get("gene?select=symbol") if g.get("symbol")})

    gene_phenotypes: dict[str, list[str]] = {}
    for gene in genes:
        rows = _get(
            "diplotype?genesymbol=eq.%s&select=generesult"
            % urllib.parse.quote(gene)
        )
        values = sorted({r["generesult"] for r in rows if r.get("generesult")})
        if values:
            gene_phenotypes[gene] = values

    recommendation_phenotypes: dict[str, set] = {}
    for row in _get("recommendation?select=phenotypes"):
        for gene, phenotype in (row.get("phenotypes") or {}).items():
            recommendation_phenotypes.setdefault(gene, set()).add(phenotype)

    standardised = {
        t["term"] for t in terms if (t.get("category") or "").startswith("Phenotype")
    }
    emitted = {v for values in gene_phenotypes.values() for v in values}
    folded = {t.casefold() for t in standardised}

    return {
        "_source": "CPIC API (api.cpicpgx.org): term, gene, diplotype, recommendation",
        "_snapshot_date": date.today().isoformat(),
        "_note": (
            "Generated by scripts/regen_cpic_vocabulary.py. Every term and "
            "definition is CPIC's own string, verbatim. Do not hand-edit."
        ),
        "_standardising_publication_pmid": "27441996",
        "_measurements": {
            "_note": (
                "Taken at snapshot time. These are the reason this file is "
                "shaped per gene and matched casefolded."
            ),
            "genes_with_diplotype_tables": len(gene_phenotypes),
            "standardised_phenotype_terms": len(standardised),
            "distinct_emitted_generesults": len(emitted),
            "emitted_but_not_standardised": sorted(
                v for v in emitted if v.casefold() not in folded
            ),
            "exact_case_matches": sorted(emitted & standardised),
            "not_established_term": "No Result",
            "not_established_is_recommendation_layer_only": "No Result"
            not in emitted,
        },
        "terms": [
            {
                "category": t.get("category"),
                "term": t.get("term"),
                "functional_definition": t.get("functionaldef") or "",
                "genetic_definition": t.get("geneticdef") or "",
                # Present in CPIC's schema and empty for every row at snapshot
                # time. Carried so its arrival is visible rather than assumed.
                "loinc": t.get("loinc") or "",
            }
            for t in sorted(terms, key=lambda t: (t.get("category") or "", t.get("term") or ""))
        ],
        "engine_terms": list(ENGINE_TERMS),
        "gene_phenotypes": gene_phenotypes,
        "recommendation_phenotypes": {
            g: sorted(v) for g, v in sorted(recommendation_phenotypes.items())
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the committed file differs from the live API",
    )
    args = parser.parse_args()

    snapshot = build()
    path = OUT / FILENAME
    rendered = json.dumps(snapshot, indent=1, sort_keys=False) + "\n"

    if args.check:
        if not path.exists():
            print(f"{path} does not exist", file=sys.stderr)
            return 1
        current = json.loads(path.read_text())
        fresh = json.loads(rendered)
        # The snapshot date moves every day and says nothing about drift.
        for blob in (current, fresh):
            blob.pop("_snapshot_date", None)
        if current != fresh:
            print(
                "CPIC vocabulary has drifted from the committed snapshot. "
                "Re-run without --check and review the diff.",
                file=sys.stderr,
            )
            return 1
        print(
            "CPIC vocabulary matches (%d genes, %d terms)."
            % (len(fresh["gene_phenotypes"]), len(fresh["terms"]))
        )
        return 0

    OUT.mkdir(parents=True, exist_ok=True)
    path.write_text(rendered)
    m = snapshot["_measurements"]
    print(
        "wrote %s: %d genes, %d standardised terms, %d emitted values, "
        "%d emitted-but-not-standardised, %d exact-case matches"
        % (
            path,
            m["genes_with_diplotype_tables"],
            m["standardised_phenotype_terms"],
            m["distinct_emitted_generesults"],
            len(m["emitted_but_not_standardised"]),
            len(m["exact_case_matches"]),
        ),
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
